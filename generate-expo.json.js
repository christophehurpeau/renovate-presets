import fs from "node:fs";
import { format } from "oxfmt";

// Packages whose versions the Expo SDK pins, read from the same sources as
// `expo install --fix` (@expo/cli getCombinedKnownVersionsAsync):
// - bundledNativeModules.json of the expo package, served by
//   api.expo.dev/v2/sdks/<sdk>/native-modules;
// - the SDK entry of api.expo.dev/v2/versions: react and react-dom
//   (facebookReactVersion), react-native and relatedPackages.
const expoApiUrl = "https://api.expo.dev/v2";

// union of the latest SDKs, so a repository still on an older SDK keeps the
// packages it pins
const sdkCount = 3;

const excludePkgNames = new Set([
  // the Expo SDK upgrade itself
  "expo",
  // tooling Expo only gives a compatible range for, shared with the non-Expo
  // workspaces of a monorepo and updated with their own rules
  "typescript",
  "jest",
  "@types/jest",
  "@babel/core",
  "metro",
]);

// released with react under the same version, absent from Expo's data
const extraPkgNames = ["react-test-renderer"];

const fetchData = async (pathname) => {
  const response = await fetch(`${expoApiUrl}/${pathname}`);
  if (!response.ok) {
    throw new Error(`${pathname}: ${response.status} ${response.statusText}`);
  }
  const { data } = await response.json();
  if (!data) throw new Error(`${pathname}: no data`);
  return data;
};

const { sdkVersions } = await fetchData("versions/latest");
const sdks = Object.keys(sdkVersions)
  .sort((a, b) => Number.parseInt(b, 10) - Number.parseInt(a, 10))
  .slice(0, sdkCount);

const pkgNames = new Set(extraPkgNames);
for (const sdk of sdks) {
  const nativeModules = await fetchData(`sdks/${sdk}/native-modules`);
  if (nativeModules.length === 0) {
    throw new Error(`SDK ${sdk}: empty native modules list`);
  }
  for (const { npmPackage } of nativeModules) pkgNames.add(npmPackage);

  const version = sdkVersions[sdk];
  for (const pkgName of Object.keys(version.relatedPackages || {})) {
    pkgNames.add(pkgName);
  }
  if (version.facebookReactVersion) {
    pkgNames.add("react");
    pkgNames.add("react-dom");
  }
  if (version.facebookReactNativeVersion) pkgNames.add("react-native");
}

const sdkMajors = sdks.map((sdk) => Number.parseInt(sdk, 10)).sort();

const config = {
  description: `Expo apps: packages whose versions the Expo SDK (SDK ${sdkMajors.join(", ")}) or alouette pins. Generated by generate-expo.json.js, do not edit.`,
  packageRules: [
    {
      description:
        "Versions pinned by the Expo SDK: updated with the SDK by `expo install --fix`",
      matchPackageNames: [...pkgNames]
        .filter((pkgName) => !excludePkgNames.has(pkgName))
        .sort(),
      enabled: false,
    },
    {
      description:
        "alouette declares exact nativewind and react-native-css peers: updated with alouette. The alouette repository re-enables them",
      matchPackageNames: ["nativewind", "react-native-css"],
      enabled: false,
    },
  ],
};

const { code: formattedConfig } = await format(
  "expo.json",
  JSON.stringify(config, null, 2),
  { printWidth: 80 },
);

fs.writeFileSync("./expo.json", formattedConfig);
